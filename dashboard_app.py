def render_network_graph(
    subgraph_data: Dict[str, Any],
    focal_src: str,
    focal_dst: str,
    highlighted_cycle_nodes: Optional[List[str]] = None,
) -> str:
    """
    Renders the 2-hop neighborhood network data from GET /api/v1/investigate/{tx_id}/subgraph
    using PyVis with custom styling, distinct color coding, and volume-weighted edges.
    """
    if not HAS_PYVIS:
        return ""

    net = Network(
        height="520px",
        width="100%",
        bgcolor="#090d16",
        font_color="#f1f5f9",
        directed=True,
    )
    net.barnes_hut(gravity=-2500, central_gravity=0.3, spring_length=160, damping=0.9)

    cycle_set = set(highlighted_cycle_nodes or [])
    nodes = subgraph_data.get("nodes", [])
    edges = subgraph_data.get("edges", [])

    for node in nodes:
        nid = node.get("id") or str(node)
        in_deg = node.get("in_degree", 0)
        out_deg = node.get("out_degree", 0)
        flow_bal = node.get("flow_balance", 0.0)

        is_src = (nid == focal_src)
        is_dst = (nid == focal_dst)
        in_cycle = (nid in cycle_set) or (in_deg > 0 and out_deg > 0 and abs(flow_bal) < 200.0 and in_deg + out_deg >= 2)

        if is_src:
            color = "#f97316"  # Orange: Focal Originator
            size = 32
            shape = "dot"
            role_desc = "FOCAL ORIGINATOR"
        elif is_dst:
            color = "#ef4444"  # Red: Focal Beneficiary
            size = 32
            shape = "dot"
            role_desc = "FOCAL BENEFICIARY"
        elif in_cycle:
            color = "#a855f7"  # Purple: Cycle / Intermediary Mule
            size = 26
            shape = "diamond"
            role_desc = "INTERMEDIARY MULE / CYCLE NODE"
        else:
            color = "#3b82f6"  # Blue: Neighbor Entity
            size = 18
            shape = "dot"
            role_desc = "NEIGHBOR ENTITY"

        net.add_node(
            nid,
            label=f"{nid}\n[{role_desc.split()[0]}]",
            color=color,
            size=size,
            shape=shape,
            title=(
                f"<b>Entity ID:</b> {nid}<br>"
                f"<b>Role:</b> {role_desc}<br>"
                f"<b>In-Degree:</b> {in_deg} | <b>Out-Degree:</b> {out_deg}<br>"
                f"<b>Net Flow Balance:</b> ${flow_bal:,.2f}"
            ),
        )

    for edge in edges:
        u = edge.get("source")
        v = edge.get("target")
        amt = float(edge.get("amount", edge.get("amount_usd", 1000.0)))
        curr = edge.get("currency", "USD")
        rail = edge.get("rail", "fiat")
        is_focal = edge.get("is_focal", False) or (u == focal_src and v == focal_dst)
        is_cycle_edge = (u in cycle_set and v in cycle_set)

        # Edge weighting based on transaction volume
        edge_weight = max(1, min(10, int(amt / 8000) + 1))

        if is_focal:
            edge_color = "#ef4444"  # Red for focal transfer
            edge_weight = max(3, edge_weight)
        elif is_cycle_edge:
            edge_color = "#a855f7"  # Purple for cycle flow
            edge_weight = max(2, edge_weight)
        else:
            edge_color = "#475569"  # Slate for normal flow

        net.add_edge(
            u,
            v,
            label=f"${amt:,.0f}" if amt < 1e6 else f"${amt/1e6:.1f}M",
            color=edge_color,
            width=edge_weight,
            title=(
                f"<b>Transfer:</b> {u} ➔ {v}<br>"
                f"<b>Amount:</b> ${amt:,.2f} {curr}<br>"
                f"<b>Rail:</b> {rail.upper()}<br>"
                f"<b>Weight:</b> {edge_weight}px"
            ),
        )

    return net.generate_html()



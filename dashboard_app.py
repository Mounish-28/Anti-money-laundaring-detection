def check_backend_health(base_url: str) -> Tuple[bool, Dict[str, Any]]:
    """Checks availability and model telemetry of the FastAPI server."""
    try:
        resp = requests.get(f"{base_url}/health", timeout=1.5)
        if resp.status_code == 200:
            return True, resp.json()
    except Exception:
        pass
    return False, {}


def fetch_all_alerts(base_url: str) -> List[Dict[str, Any]]:
    """Fetches alert list from backend API, or falls back to in-memory agent."""
    is_live, _ = check_backend_health(base_url)
    if is_live:
        try:
            resp = requests.get(f"{base_url}/api/v1/alerts", timeout=3.0)
            if resp.status_code == 200:
                return resp.json().get("alerts", [])
        except Exception:
            pass

    # Local fallback to in-memory agent
    items = []
    for tx_id, tx in reversed(list(agent_engine.transactions.items())):
        amount = tx.get("amount_usd", tx.get("amount", 0.0))
        items.append({
            "tx_id": tx_id,
            "risk_score": tx.get("aggregate_risk_score", tx.get("risk_score", 0.0)),
            "severity_tier": tx.get("severity_tier", "LOW_NOMINAL"),
            "alert_triggered": tx.get("alert_triggered", False),
            "triage_status": tx.get("triage_status", "OPEN"),
            "triage_note": tx.get("triage_note", ""),
            "source_node": tx.get("source_node", tx.get("account_from", "")),
            "target_node": tx.get("target_node", tx.get("account_to", "")),
            "amount_usd": amount,
            "amount": amount,
            "currency": tx.get("currency", "USD"),
            "rail": tx.get("rail", "fiat"),
            "reason_codes": tx.get("reason_codes", []),
            "timestamp": tx.get("timestamp", ""),
            "regulatory_breach": amount >= 10000.0 or tx.get("regulatory_breach", False),
            "audit_hash": tx.get("audit_hash", ""),
        })
    return items


def fetch_subgraph_data(base_url: str, tx_id: str) -> Dict[str, Any]:
    """Fetches 2-hop neighborhood from GET /api/v1/investigate/{tx_id}/subgraph."""
    is_live, _ = check_backend_health(base_url)
    if is_live:
        try:
            resp = requests.get(f"{base_url}/api/v1/investigate/{tx_id}/subgraph", timeout=3.0)
            if resp.status_code == 200:
                return resp.json()
        except Exception:
            pass

    # Local in-process fallback
    return agent_engine.extract_2hop_subgraph(tx_id=tx_id)


def fetch_investigation_brief(base_url: str, tx_id: str) -> Dict[str, Any]:
    """Pulls full forensic brief from backend API, or generates via xai_explainer."""
